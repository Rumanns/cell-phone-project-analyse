# Preparo do ambiente, coleta e limpeza de dados

# Antes de mais nada é necessário criar um ambiente no qual faremos a instalação das bibliotecas e configurações necessárias.
# Considerando que o python está instalado. Vamos a passo a passo:

# Passo 1, criar uma máquina virtual:
#    Pelo CMD, entre numa pasta específica > use o comando "python -m venv NomeDaMaquinaVirtual" para criar uma VM

# Passo 2, ativar a máquina virtual que foi criada:
#    No CMD, acesse a pasta criada e vá até a pasta "Scripts"
#    Dentro da pasta Scripts, pelo CMD, dê o comando "activate"
#    Agora a VM está criada, acessada e pronta para uso, mas sem as bibliotecas

# Passo 3, instalando bibliotecas:
#    Ainda dentro da VM, pelo CMD, pode dar os comandos "pip install nomeDaBiblioteca" que vai instalar a biblioteca que você quiser
#    Se os nomes das bilbiotecas estiverem em um arquivo TXT, pode usar "pip install "pip install -r requirements.txt"


# Pronto, ambiente configurado!
# Agora basta importar os dados para um dataframe e começar alimpar esses dados.




